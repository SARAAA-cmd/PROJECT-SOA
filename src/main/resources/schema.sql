-- =============================================================
-- Schéma de la plateforme de gestion des stages
-- Compatible H2 et PostgreSQL
-- =============================================================

-- ---------- Sécurité ----------
CREATE TABLE IF NOT EXISTS utilisateur (
    username      VARCHAR(50)  PRIMARY KEY,
    password_hash VARCHAR(200) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    ref_id        VARCHAR(50)
);

-- Empreinte SHA-256 de la clé d'API REST (la clé elle-même n'est jamais stockée)
ALTER TABLE utilisateur ADD COLUMN IF NOT EXISTS api_key_hash VARCHAR(64);

-- ---------- Service 1 : Étudiants (SOAP) ----------
CREATE TABLE IF NOT EXISTS etudiant (
    matricule        VARCHAR(20)  PRIMARY KEY,
    nom              VARCHAR(80)  NOT NULL,
    prenom           VARCHAR(80)  NOT NULL,
    email            VARCHAR(120) NOT NULL UNIQUE,
    telephone        VARCHAR(20),
    adresse          VARCHAR(200),
    filiere          VARCHAR(80)  NOT NULL,
    niveau           VARCHAR(5)   NOT NULL,
    competences      VARCHAR(500),
    statut           VARCHAR(20)  NOT NULL,
    date_inscription DATE         NOT NULL
);

-- ---------- Service 2 : Entreprises (SOAP) ----------
CREATE TABLE IF NOT EXISTS entreprise (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raison_sociale      VARCHAR(120) NOT NULL UNIQUE,
    secteur_activite    VARCHAR(80)  NOT NULL,
    adresse             VARCHAR(200),
    ville               VARCHAR(80),
    email               VARCHAR(120) NOT NULL,
    telephone           VARCHAR(20),
    site_web            VARCHAR(200),
    contact_nom         VARCHAR(120) NOT NULL,
    contact_fonction    VARCHAR(80),
    contact_email       VARCHAR(120) NOT NULL,
    contact_telephone   VARCHAR(20),
    referencee          BOOLEAN      NOT NULL,
    date_referencement  DATE
);

-- ---------- Service 3 : Offres de stage (SOAP) ----------
CREATE TABLE IF NOT EXISTS offre (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entreprise_id        BIGINT       NOT NULL,
    titre                VARCHAR(150) NOT NULL,
    description          VARCHAR(2000) NOT NULL,
    competences_requises VARCHAR(500),
    duree_mois           INT          NOT NULL,
    date_limite          DATE         NOT NULL,
    nombre_places        INT          NOT NULL,
    places_disponibles   INT          NOT NULL,
    filieres_ciblees     VARCHAR(300),
    niveau_minimum       VARCHAR(5),
    lieu                 VARCHAR(100),
    statut               VARCHAR(20)  NOT NULL,
    date_publication     DATE         NOT NULL
);

-- ---------- Service 4 : Candidatures (REST) ----------
CREATE TABLE IF NOT EXISTS candidature (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule            VARCHAR(20)  NOT NULL,
    nom_etudiant         VARCHAR(170),
    offre_id             BIGINT       NOT NULL,
    titre_offre          VARCHAR(150),
    entreprise_id        BIGINT,
    lettre_motivation    VARCHAR(4000),
    cv_url               VARCHAR(300),
    score_compatibilite  INT,
    statut               VARCHAR(30)  NOT NULL,
    motif                VARCHAR(500),
    process_instance_id  VARCHAR(64),
    date_depot           TIMESTAMP    NOT NULL,
    date_mise_a_jour     TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS candidature_historique (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id  BIGINT      NOT NULL,
    ancien_statut   VARCHAR(30),
    nouveau_statut  VARCHAR(30) NOT NULL,
    commentaire     VARCHAR(500),
    auteur          VARCHAR(50),
    date_changement TIMESTAMP   NOT NULL
);

-- ---------- Service 5 : Notifications (REST) ----------
CREATE TABLE IF NOT EXISTS notification (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type              VARCHAR(40)  NOT NULL,
    destinataire_type VARCHAR(20)  NOT NULL,
    destinataire_id   VARCHAR(50)  NOT NULL,
    email             VARCHAR(120),
    sujet             VARCHAR(200) NOT NULL,
    message           VARCHAR(4000) NOT NULL,
    canal             VARCHAR(20)  NOT NULL,
    statut            VARCHAR(20)  NOT NULL,
    candidature_id    BIGINT,
    offre_id          BIGINT,
    date_envoi        TIMESTAMP    NOT NULL,
    lue               BOOLEAN      NOT NULL
);

-- ---------- Service 6 : Suivi des stages (REST) ----------
CREATE TABLE IF NOT EXISTS stage (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id       BIGINT       NOT NULL UNIQUE,
    matricule            VARCHAR(20)  NOT NULL,
    nom_etudiant         VARCHAR(170),
    offre_id             BIGINT       NOT NULL,
    titre_offre          VARCHAR(150),
    entreprise_id        BIGINT       NOT NULL,
    nom_entreprise       VARCHAR(120),
    sujet                VARCHAR(300),
    date_debut           DATE         NOT NULL,
    date_fin             DATE         NOT NULL,
    tuteur_entreprise    VARCHAR(120),
    encadrant_academique VARCHAR(120),
    statut               VARCHAR(20)  NOT NULL,
    date_creation        TIMESTAMP    NOT NULL
);

CREATE TABLE IF NOT EXISTS compte_rendu (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id      BIGINT        NOT NULL,
    periode       VARCHAR(80)   NOT NULL,
    contenu       VARCHAR(4000) NOT NULL,
    auteur        VARCHAR(120),
    date_depot    TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS evaluation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id      BIGINT        NOT NULL,
    type          VARCHAR(20)   NOT NULL,
    evaluateur    VARCHAR(120)  NOT NULL,
    note          DECIMAL(4,2)  NOT NULL,
    appreciation  VARCHAR(2000),
    date_evaluation TIMESTAMP   NOT NULL
);

-- Migration : niveaux LMD -> années du cycle ingénieur INPT (sans effet sur une base déjà migrée)
UPDATE etudiant SET niveau = CASE WHEN niveau IN ('L1', 'L2', 'L3') THEN 'INE1' WHEN niveau = 'M1' THEN 'INE2' ELSE 'INE3' END
    WHERE niveau IN ('L1', 'L2', 'L3', 'M1', 'M2', 'D');
UPDATE offre SET niveau_minimum = CASE WHEN niveau_minimum IN ('L1', 'L2', 'L3') THEN 'INE1' WHEN niveau_minimum = 'M1' THEN 'INE2' ELSE 'INE3' END
    WHERE niveau_minimum IN ('L1', 'L2', 'L3', 'M1', 'M2', 'D');
